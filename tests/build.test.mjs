import test from 'node:test';
import assert from 'node:assert/strict';
import { load } from './harness.mjs';

test('buildInfo: generated by make, with a label for Settings (B2)', () => {
	const BuildInfo = load()('buildInfo');
	assert.match(BuildInfo.time, /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
	assert.match(BuildInfo.label, /^Built \d{4}-\d\d-\d\d \d\d:\d\d UTC( · [0-9a-f]+(-dirty)?)?$/);
	assert.ok(BuildInfo.label.includes(BuildInfo.time.slice(0, 10)));
	assert.ok(BuildInfo.id.startsWith(BuildInfo.time.replace(/[-:]/g, '')), BuildInfo.id);
	if (BuildInfo.commit) assert.ok(BuildInfo.id.endsWith(`-${BuildInfo.commit}`));
});
