import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { load, ROOT } from './harness.mjs';

test('buildInfo: generated by make, with a label for Settings (B2)', () => {
	const BuildInfo = load()('buildInfo');
	assert.match(BuildInfo.time, /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
	assert.match(BuildInfo.label, /^Built \d{4}-\d\d-\d\d \d\d:\d\d UTC( · [0-9a-f]+(-dirty)?)?$/);
	assert.ok(BuildInfo.label.includes(BuildInfo.time.slice(0, 10)));
	assert.ok(BuildInfo.id.startsWith(BuildInfo.time.replace(/[-:]/g, '')), BuildInfo.id);
	if (BuildInfo.commit) assert.ok(BuildInfo.id.endsWith(`-${BuildInfo.commit}`));
});

// Builds into a temporary directory, so the tree's build/ and dist/ are untouched.
const makeInTemp = (plugins) => {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gh-memo-build-'));
	const run = spawnSync('make', ['-s', `BUILD_DIR=${dir}/build`, `DIST_DIR=${dir}/dist`, `PLUGINS=${plugins}`, 'build'],
		{ cwd: ROOT, encoding: 'utf8' });
	const read = (file) => fs.readFileSync(path.join(dir, file), 'utf8');
	return { run, read, cleanup: () => fs.rmSync(dir, { recursive: true, force: true }) };
};
const builtIn = (html) => [...html.matchAll(/sourceURL=\S*?\/?(plugins\/[\w/]+)\.js/g)].map(m => m[1]);

test('plugins: the registry lists the default plugins in priority order, unsupported last; panel is not one', () => {
	const require = load();
	const { plugins } = require('plugins/registry');
	const names = ['image', 'pdf', 'markdown', 'text', 'unsupported'];
	assert.equal(plugins.length, names.length);
	names.forEach((n, i) => assert.equal(plugins[i], require(`plugins/${n}`), n));
});

test('plugins: make PLUGINS=... builds in only those, in the order given', () => {
	const { run, read, cleanup } = makeInTemp('text markdown');
	try {
		assert.equal(run.status, 0, run.stderr);
		assert.match(read('build/plugins/registry.js'), /\['plugins\/text', 'plugins\/markdown', 'plugins\/unsupported'\]/);
		assert.deepEqual(builtIn(read('dist/index.html')),
			['plugins/registry', 'plugins/markdown', 'plugins/text', 'plugins/textEditor', 'plugins/unsupported']);
	} finally { cleanup(); }
});

test('plugins: an unknown name stops the build', () => {
	const { run, cleanup } = makeInTemp('text gizmo');
	try {
		assert.notEqual(run.status, 0);
		assert.match(run.stderr, /Unknown plugin\(s\): gizmo\. Available: image markdown panel pdf text/);
	} finally { cleanup(); }
});

test('plugins: a dependency on a module that is not built in stops the build', () => {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gh-memo-deps-'));
	try {
		fs.writeFileSync(path.join(dir, 'a.js'), "define('ui/a',\n\t['lib/b', 'plugins/gone/helper'],\n\t(B, H) => ({}));\n");
		fs.writeFileSync(path.join(dir, 'b.js'), "define('lib/b', [], () => ({}));\n");
		const ok = spawnSync('awk', ['-f', 'checkdeps.awk', path.join(dir, 'b.js')], { cwd: ROOT, encoding: 'utf8' });
		assert.equal(ok.status, 0, ok.stderr);
		const bad = spawnSync('awk', ['-f', 'checkdeps.awk', path.join(dir, 'a.js'), path.join(dir, 'b.js')], { cwd: ROOT, encoding: 'utf8' });
		assert.equal(bad.status, 1);
		assert.equal(bad.stderr.trim(), `error: ui/a (${path.join(dir, 'a.js')}) needs plugins/gone/helper, which is not built in`);
	} finally { fs.rmSync(dir, { recursive: true, force: true }); }
});
